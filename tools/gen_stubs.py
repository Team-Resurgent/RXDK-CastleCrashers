#!/usr/bin/env python3
"""Logging stubs for the imports the runtime does not implement yet.

  gen_stubs.py <generated dir> <runtime dir>

The generated code calls every import as __imp__<name>. Each one no
IMPORT(<name>) in the runtime defines gets a stub that logs its first call and
returns 0, written to <generated dir>/ppc_import_stubs.cpp.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path


def main() -> int:
    generated, runtime = Path(sys.argv[1]), Path(sys.argv[2])
    declared = set(re.findall(r"PPC_EXTERN_FUNC\(__imp__(\w+)\)", (generated / "ppc_recomp_shared.h").read_text()))
    defined = set()
    for path in generated.glob("ppc_recomp.*.cpp"):
        defined |= set(re.findall(r"PPC_FUNC_IMPL\(__imp__(\w+)\)", path.read_text()))
    implemented = set()
    for path in runtime.rglob("*.cpp"):
        implemented |= set(re.findall(r"^IMPORT\((\w+)\)", path.read_text(), re.M))
    missing = sorted(declared - defined - implemented)
    lines = ["// Generated by tools/gen_stubs.py: imports the runtime does not implement.",
             '#include "runtime/kernel.h"', "",
             "static void stub(const char* name, bool& said) {",
             "    if (!said)",
             r'        log("stub: %s\n", name);',
             "    said = true;",
             "}", ""]
    for name in missing:
        lines.append(f'IMPORT({name}) {{ static bool said; stub("{name}", said); ctx.r3.u64 = 0; }}')
    (generated / "ppc_import_stubs.cpp").write_text("\n".join(lines) + "\n")
    print(f"gen_stubs: {len(implemented)} imports implemented, {len(missing)} stubbed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

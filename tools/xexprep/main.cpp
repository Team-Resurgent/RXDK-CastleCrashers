// xexprep <default.xex> <image.bin> <imports.inc>
// xexprep --patch <default.xex> <default.xexp> <patched.xex>
//
// Writes the title's memory image as XenonRecomp sees it (decrypted,
// decompressed, at its load address): the Xbox runtime loads it into guest
// memory, so the data the recompiled code reads matches what it was
// recompiled from.
//
// imports.inc lists the import records the XEX loader fills in, one
// PPC_IMPORT(slot, thunk, library, ordinal) per record: a function import's
// record gets its thunk's address (thunk != 0), a variable import's record
// the address of the runtime's copy of that variable (thunk == 0).
//
// --patch applies a title update's delta (default.xexp) to the base XEX.
#include <cstdio>
#include <cstring>
#include <string_view>
#include <vector>
#include <image.h>
#include <xex.h>
#include <xex_patcher.h>

int main(int argc, char** argv)
{
    if (argc == 5 && std::string_view(argv[1]) == "--patch")
    {
        if (XexPatcher::apply(argv[2], argv[3], argv[4]) != XexPatcher::Result::Success)
        {
            std::fprintf(stderr, "xexprep: cannot apply %s to %s\n", argv[3], argv[2]);
            return 1;
        }
        std::printf("xexprep: %s\n", argv[4]);
        return 0;
    }
    if (argc != 4)
    {
        std::fprintf(stderr, "usage: xexprep <default.xex> <image.bin> <imports.inc>\n");
        return 2;
    }
    FILE* in = std::fopen(argv[1], "rb");
    if (!in)
    {
        std::fprintf(stderr, "xexprep: cannot open %s\n", argv[1]);
        return 1;
    }
    std::vector<uint8_t> xex;
    uint8_t chunk[1 << 16];
    for (size_t n; (n = std::fread(chunk, 1, sizeof(chunk), in)) > 0;)
        xex.insert(xex.end(), chunk, chunk + n);
    std::fclose(in);

    Image image = Image::ParseImage(xex.data(), xex.size());
    if (!image.data)
    {
        std::fprintf(stderr, "xexprep: %s is not an XEX this tool can read\n", argv[1]);
        return 1;
    }
    FILE* out = std::fopen(argv[2], "wb");
    if (!out || std::fwrite(image.data.get(), 1, image.size, out) != image.size)
    {
        std::fprintf(stderr, "xexprep: cannot write %s\n", argv[2]);
        return 1;
    }
    std::fclose(out);

    // ParseImage replaced every function thunk with this stub and byte-swapped
    // the import records to host order.
    static const uint32_t stub[4] = { 0x00000060, 0x00000060, 0x00000060, 0x2000804E };
    auto isStub = [&](uint32_t address) { return std::memcmp(image.Find(address), stub, sizeof(stub)) == 0; };
    out = std::fopen(argv[3], "w");
    if (!out)
    {
        std::fprintf(stderr, "xexprep: cannot write %s\n", argv[3]);
        return 1;
    }
    std::fprintf(out, "// Generated by tools/xexprep from the title's default.xex.\n");
    auto* imports = reinterpret_cast<const Xex2ImportHeader*>(getOptHeaderPtr(xex.data(), XEX_HEADER_IMPORT_LIBRARIES));
    std::vector<std::string_view> names;
    const char* strings = reinterpret_cast<const char*>(imports + 1);
    for (size_t i = 0, offset = 0; i < imports->numImports; i++)
    {
        names.emplace_back(strings + offset);
        offset += ((names.back().length() + 1) + 3) & ~3;
    }
    auto* library = (const Xex2ImportLibrary*)(((const char*)imports) + sizeof(Xex2ImportHeader) + imports->sizeOfStringTable);
    size_t records = 0;
    for (size_t i = 0; i < names.size(); i++)
    {
        auto* descriptors = (const Xex2ImportDescriptor*)(library + 1);
        const char* id = names[i] == "xboxkrnl.exe" ? "PPC_KERNEL" : names[i] == "xam.xex" ? "PPC_XAM" : nullptr;
        if (!id)
        {
            std::fprintf(stderr, "xexprep: imports from %.*s are not supported\n", int(names[i].size()), names[i].data());
            return 1;
        }
        for (size_t im = 0; im < library->numberOfImports; im++)
        {
            uint32_t slot = descriptors[im].firstThunk;
            if (isStub(slot))
                continue;
            uint32_t value;
            std::memcpy(&value, image.Find(slot), 4);
            uint32_t thunk = 0;
            if (im + 1 < library->numberOfImports && isStub(descriptors[im + 1].firstThunk))
                thunk = descriptors[im + 1].firstThunk;
            std::fprintf(out, "PPC_IMPORT(0x%08X, 0x%08X, %s, 0x%03X)\n", slot, thunk, id, value & 0xFFFF);
            records++;
        }
        library = (const Xex2ImportLibrary*)((const char*)(library + 1) + library->numberOfImports * sizeof(Xex2ImportDescriptor));
    }
    std::fclose(out);
    std::printf("xexprep: image base %08zX size %X entry %08zX, %zu import records\n",
        image.base, image.size, image.entry_point, records);
    return 0;
}
